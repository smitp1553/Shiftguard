# runs checkov and shiftguard on the labs and writes docs/benchmark.md
# usage: python -m benchmark.compare
import json
import shutil
import subprocess
import sys
from pathlib import Path

from shiftguard.graph import build_graph
from shiftguard.parser import load_plan
from shiftguard.paths import find_paths
from shiftguard.techniques.common import principals

ROOT = Path(__file__).resolve().parent.parent
LABS = ["lab-vulnerable", "lab-safe", "lab-chain"]

# the checkov checks that are really about privilege escalation / admin access
# (other ones like SSO or "attach to groups" are hygiene, not escalation)
# CKV_AWS_274 (AdministratorAccess attached) is left out on purpose: every account has some admin, so it fires on the admin user even when nobody can reach it
ESCALATION = {
    "CKV_AWS_286": "policy allows privilege escalation",
    "CKV_AWS_289": "permissions management without constraints",
    "CKV_AWS_61": "role can be assumed by any principal",
}


def run_checkov(args):
    # returns the list of failed checks and the number of passed checks
    # use the checkov program if it is on the PATH, else run it as a module
    exe = shutil.which("checkov")
    base = [exe] if exe else [sys.executable, "-m", "checkov.main"]
    cmd = base + [*args, "-o", "json", "--soft-fail"]
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    try:
        data = json.loads(p.stdout)
    except ValueError:
        return None  # checkov printed no json, nothing was scanned
    if isinstance(data, dict):
        data = [data]
    failed, passed = [], 0
    for d in data:
        res = d.get("results", {})
        failed += res.get("failed_checks", [])
        passed += len(res.get("passed_checks", []))
    return {"failed": failed, "passed": passed}


def short(resource):
    # "aws_iam_user_policy.dev_alice_inline" -> "dev_alice_inline"
    return resource.split(".")[-1]


def words(name):
    # "user:dev-alice" -> "dev_alice"
    return name.split(":")[-1].replace("-", "_")


def names_in_finding(f):
    names = {words(f["principal"])}
    for s in f["steps"]:
        names.add(words(s["to"]))
    names.discard("admin")
    return names


def checkov_touches(finding, failed):
    # heuristic: does a failed checkov check sit on a resource named after the principal or its target
    names = names_in_finding(finding)
    hits = [c for c in failed if c["check_id"] in ESCALATION and any(n in short(c["resource"]) for n in names)]
    return hits


def main():
    out = ["# Benchmark: ShiftGuard vs Checkov", ""]
    out.append("Generated by `python -m benchmark.compare`. Checkov is run as `checkov -d` on the .tf files and as `checkov -f` on the plan json, both with --soft-fail.")
    out.append("")

    for lab in LABS:
        plan = ROOT / "terraform" / lab / "plan.json"
        if not plan.exists():
            continue  # lab-chain has no plan.json until you run terraform on it
        g = build_graph(load_plan(str(plan)))
        findings = find_paths(g)
        total = len(principals(g))

        tf = run_checkov(["-d", f"terraform/{lab}", "--framework", "terraform"])
        pl = run_checkov(["-f", f"terraform/{lab}/plan.json", "--framework", "terraform_plan"])

        out.append(f"## {lab}")
        out.append("")
        out.append(f"ShiftGuard: {len(findings)} of {total} principals can reach admin.")
        for label, r in (("Checkov on .tf files", tf), ("Checkov on plan.json", pl)):
            if r is None:
                out.append(f"- {label}: no output (nothing scanned)")
            else:
                esc = [c for c in r["failed"] if c["check_id"] in ESCALATION]
                hygiene = len(r["failed"]) - len(esc)
                esc_ids = sorted({c["check_id"] for c in esc})
                out.append(f"- {label}: {len(r['failed'])} failed, {r['passed']} passed. Escalation-related failures: {len(esc)} ({', '.join(esc_ids) if esc_ids else 'none'}). Other failures (hygiene, noise for this question): {hygiene}")
        out.append("")

        if findings:
            out.append("| principal | ShiftGuard path | Checkov escalation check on .tf? | Checkov escalation check on plan? |")
            out.append("|---|---|---|---|")
            for f in findings:
                path = " -> ".join([f["principal"]] + [s["to"] for s in f["steps"]])
                cells = []
                for r in (tf, pl):
                    if r is None:
                        cells.append("n/a")
                        continue
                    hits = checkov_touches(f, r["failed"])
                    cells.append("yes: " + ", ".join(sorted({c["check_id"] for c in hits})) if hits else "no")
                out.append(f"| {f['principal']} | {path} ({f['steps'][0]['technique']}) | {cells[0]} | {cells[1]} |")
            out.append("")

    out.append("## How to read this")
    out.append("")
    out.append("- Escalation checks counted: " + ", ".join(f"{k} ({v})" for k, v in ESCALATION.items()) + ".")
    out.append("- A \"yes\" only means one of those checks failed on a resource whose name matches the principal or its target. It does not mean Checkov understood the whole path.")
    out.append("- The matching is by resource name, so it is a rough guess (TODO: match by real resource address).")
    out.append("- Checkov has hundreds of checks for other things (encryption, logging, networking). ShiftGuard only does IAM escalation, so this is not a fair fight on coverage, only on this one question.")
    text = "\n".join(out) + "\n"

    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "benchmark.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()